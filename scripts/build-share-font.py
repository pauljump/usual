"""Generate raster glyphs, not a font file, for the lightweight Worker PNG renderer.
Run on macOS with Pillow; generated output is committed so deployment needs no Python.
"""
import base64, json, zlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
chars = ''.join(chr(i) for i in range(32, 256)) + '’‘“”–—…'
fonts = {}
for name,size,file in [('title',56,'Arial Bold.ttf'),('small',24,'Arial.ttf')]:
 font=ImageFont.truetype('/System/Library/Fonts/Supplemental/'+file,size)
 data=bytearray(); glyphs={}
 for ch in chars:
  l,t,r,b=font.getbbox(ch)
  w=max(1,r-l);h=max(1,b-t)
  im=Image.new('L',(w,h));ImageDraw.Draw(im).text((-l,-t),ch,font=font,fill=255)
  glyphs[ch]=[len(data),w,h,l,t,round(font.getlength(ch))]
  data.extend(im.tobytes())
 fonts[name]={'glyphs':glyphs,'data':base64.b64encode(zlib.compress(data,9)).decode()}
Path('src/share/font-data.ts').write_text('// Generated by scripts/build-share-font.py. Raster letterforms only.\nexport const fonts = '+json.dumps(fonts,ensure_ascii=True,separators=(',',':'))+';\n')
