// Prints a Wrangler config for your own Thought Swarm instance, derived from
// the committed wrangler.toml, without touching it.
//   node scripts/own-config.mjs <d1-database-id> [host] [workers.dev url] > wrangler.own.toml
// With a host, the Worker gets that custom domain (its zone must be in your
// Cloudflare account). Without one it is served on workers.dev only.
import { readFileSync } from "node:fs";

const [id, host, workersUrl] = process.argv.slice(2);
if (!/^[0-9a-f-]{36}$/.test(id ?? "")) {
  console.error("Usage: node scripts/own-config.mjs <d1-database-id> [host] [workers.dev url]");
  process.exit(1);
}
const name = host?.replace(/^https?:\/\//, "").replace(/\/$/, "");
const base = name ? `https://${name}` : (workersUrl || "http://localhost:8787").replace(/\/$/, "");

let toml = readFileSync(new URL("../wrangler.toml", import.meta.url), "utf8")
  .replace(/^routes = .*\n/m, name ? `routes = [{ pattern = "${name}", custom_domain = true }]\n` : "")
  .replace(/^PUBLIC_BASE_URL = ".*"$/m, `PUBLIC_BASE_URL = "${base}"`)
  .replace(/^database_id = ".*"$/m, `database_id = "${id}"`);
process.stdout.write(`# Generated by scripts/own-config.mjs for your own instance. Not committed.\n${toml}`);
